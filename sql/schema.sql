-- =====================================================================
-- StockSense — database schema + starter seed data
--
-- IMPORTANT — import with utf8mb4, not your client's default charset.
-- The em-dashes and curly text below are correct UTF-8 in this file; if you
-- import with a mismatched connection charset (e.g. latin1), they will come
-- out garbled (e.g. "SOXX —" becomes "SOXX â€”") even though the file itself
-- is fine. Use one of:
--   mysql --default-character-set=utf8mb4 -u root -p stocksense < sql/schema.sql
-- or, in phpMyAdmin: on the Import tab, set "Character set of the file" to
-- utf8mb4 before importing. Do NOT use a plain `mysql -u root -p stocksense
-- < schema.sql` — it relies on the client's default charset, which is often
-- not utf8mb4.
-- =====================================================================

CREATE DATABASE IF NOT EXISTS stocksense CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;
USE stocksense;

-- ---------------------------------------------------------------------
-- Companies tracked by the app, plus the sector benchmark (SOXX ETF),
-- stored the same way (segment = 'benchmark') so its price history
-- can be queried with the exact same code path as any stock.
-- ---------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS companies (
    ticker      VARCHAR(10) PRIMARY KEY,
    name        VARCHAR(100) NOT NULL,
    segment     VARCHAR(50)  NOT NULL,   -- foundry | fabless | equipment | idm | memory | benchmark
    is_benchmark TINYINT(1) NOT NULL DEFAULT 0
) ENGINE=InnoDB;

-- ---------------------------------------------------------------------
-- Daily price history — used for both individual stocks and SOXX.
-- ---------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS price_history (
    id          INT AUTO_INCREMENT PRIMARY KEY,
    ticker      VARCHAR(10) NOT NULL,
    trade_date  DATE NOT NULL,
    close_price DECIMAL(10,2) NOT NULL,
    pct_change  DECIMAL(6,3) NOT NULL,
    UNIQUE KEY uniq_ticker_date (ticker, trade_date),
    FOREIGN KEY (ticker) REFERENCES companies(ticker) ON DELETE CASCADE
) ENGINE=InnoDB;

-- ---------------------------------------------------------------------
-- News articles — real or simulated, tagged to one of the 5 categories.
-- Carries the extra fields called out in the charter's minimum schema
-- (source_url, notes, graph) plus the stock/sector percentage moves
-- used for the stock-vs-sector comparison shown after each quiz answer.
-- ---------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS news_articles (
    id                   INT AUTO_INCREMENT PRIMARY KEY,
    ticker               VARCHAR(10) NULL,
    category             ENUM('geopolitical','earnings','macro','corporate','supply_chain') NOT NULL,
    headline             VARCHAR(255) NOT NULL,
    summary              TEXT NOT NULL,
    source               VARCHAR(50) NOT NULL,     -- finnhub | alphavantage | manual_simulated
    source_url           VARCHAR(500) NULL,
    published_at         DATETIME NOT NULL,
    is_simulated         TINYINT(1) NOT NULL DEFAULT 0,
    price_change_stock   DECIMAL(6,3) NULL,        -- stock's % move around this event
    price_change_sector  DECIMAL(6,3) NULL,        -- SOXX's % move over the same window
    notes                TEXT NULL,                -- internal authoring notes
    graph_path            VARCHAR(255) NULL,        -- optional path to a saved chart image
    FOREIGN KEY (ticker) REFERENCES companies(ticker) ON DELETE SET NULL
) ENGINE=InnoDB;

-- ---------------------------------------------------------------------
-- Simulated pre-event price trend, day -5 through day 0 (event day),
-- for the "before" chart shown on some quiz questions. Values are made
-- up for visual flavor only — they don't need to be historically
-- accurate. The actual day +1 reveal after the user answers comes from
-- news_articles.price_change_stock, not from this table.
-- ---------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS news_price_trend (
    id               INT AUTO_INCREMENT PRIMARY KEY,
    news_article_id  INT NOT NULL,
    day_offset       TINYINT NOT NULL,        -- -5 .. 0, where 0 = event day
    close_price      DECIMAL(10,2) NOT NULL,  -- simulated close, indexed to 100.00 at day -5
    pct_change        DECIMAL(6,3) NOT NULL,   -- simulated day-over-day % change
    UNIQUE KEY uniq_article_day (news_article_id, day_offset),
    FOREIGN KEY (news_article_id) REFERENCES news_articles(id) ON DELETE CASCADE
) ENGINE=InnoDB;

-- ---------------------------------------------------------------------
-- Lessons — the "Education" trail content, grouped by category.
-- ---------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS lessons (
    id          INT AUTO_INCREMENT PRIMARY KEY,
    category    ENUM('geopolitical','earnings','macro','corporate','supply_chain') NOT NULL,
    title       VARCHAR(150) NOT NULL,
    body_html   TEXT NOT NULL,
    sort_order  INT NOT NULL DEFAULT 0
) ENGINE=InnoDB;

-- ---------------------------------------------------------------------
-- Quiz items — a POOL per category. quiz.php pulls a random subset each
-- time, so redoing a category serves different questions. Two flavors,
-- both allowed in the same pool:
--   'real_news' -> tied to a news_articles row, answer = what actually happened
--   'concept'   -> tests lesson theory directly, no news_article_id needed
-- ---------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS quiz_items (
    id               INT AUTO_INCREMENT PRIMARY KEY,
    category         ENUM('geopolitical','earnings','macro','corporate','supply_chain') NOT NULL,
    question_type    ENUM('real_news','concept') NOT NULL DEFAULT 'real_news',
    news_article_id  INT NULL,
    question_text    VARCHAR(255) NOT NULL,
    option_a         VARCHAR(120) NOT NULL,
    option_b         VARCHAR(120) NOT NULL,
    option_c         VARCHAR(120) NOT NULL,
    correct_option   CHAR(1) NOT NULL,      -- 'a' | 'b' | 'c'
    explanation      TEXT NOT NULL,
    show_price_trend TINYINT(1) NOT NULL DEFAULT 0,  -- 1 = render the day -5..0 chart from news_price_trend
    FOREIGN KEY (news_article_id) REFERENCES news_articles(id) ON DELETE SET NULL
) ENGINE=InnoDB;

-- Adds show_price_trend to a quiz_items table that already existed before this
-- column was introduced (no-op on a fresh database, since the CREATE TABLE above
-- already includes it). MySQL has no ADD COLUMN IF NOT EXISTS, so check first.
SET @col_exists = (SELECT COUNT(*) FROM information_schema.COLUMNS
    WHERE TABLE_SCHEMA = DATABASE() AND TABLE_NAME = 'quiz_items' AND COLUMN_NAME = 'show_price_trend');
SET @add_col_sql = IF(@col_exists = 0,
    'ALTER TABLE quiz_items ADD COLUMN show_price_trend TINYINT(1) NOT NULL DEFAULT 0 AFTER explanation',
    'SELECT 1');
PREPARE add_col_stmt FROM @add_col_sql;
EXECUTE add_col_stmt;
DEALLOCATE PREPARE add_col_stmt;

-- ---------------------------------------------------------------------
-- Users — accounts created on pages/login.php (Register tab). password_hash holds
-- password_hash() output, never the plain password. The seeded "guest"
-- row (id = 1) predates login; it has no password, so it cannot log in.
-- ---------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS users (
    id             INT AUTO_INCREMENT PRIMARY KEY,
    username       VARCHAR(50) UNIQUE NOT NULL,
    password_hash  VARCHAR(255) NULL,
    created_at     DATETIME DEFAULT CURRENT_TIMESTAMP
) ENGINE=InnoDB;

-- ---------------------------------------------------------------------
-- Per-category learning-path preference. Unlike a single global choice,
-- the charter's flow lets the user pick quiz-first or lesson-first
-- separately for EACH category, so this is keyed on (user, category).
-- ---------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS user_category_prefs (
    user_id        INT NOT NULL,
    category       ENUM('geopolitical','earnings','macro','corporate','supply_chain') NOT NULL,
    preferred_flow ENUM('education_first','quiz_first') NOT NULL,
    PRIMARY KEY (user_id, category),
    FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE CASCADE
) ENGINE=InnoDB;

-- ---------------------------------------------------------------------
-- Quiz attempt log — every answer a user submits.
-- session_id groups the rows from one quiz.php submission, so the
-- dashboard can score each attempt separately. Existing databases:
-- run sql/migrations/001_quiz_attempts_session_id.sql.
-- ---------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS quiz_attempts (
    id            INT AUTO_INCREMENT PRIMARY KEY,
    user_id       INT NOT NULL,
    session_id    VARCHAR(40) NOT NULL,
    quiz_item_id  INT NOT NULL,
    chosen_option CHAR(1) NOT NULL,
    is_correct    TINYINT(1) NOT NULL,
    attempted_at  DATETIME DEFAULT CURRENT_TIMESTAMP,
    FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE CASCADE,
    FOREIGN KEY (quiz_item_id) REFERENCES quiz_items(id) ON DELETE CASCADE
) ENGINE=InnoDB;

-- ---------------------------------------------------------------------
-- Answers — each user's CURRENT answer to each quiz question.
-- One row per (user, question): answering the same question again updates
-- that row instead of adding a new one (quiz_attempts above keeps the full
-- history). Existing databases: run sql/migrations/003_login_answers.sql.
-- ---------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS answers (
    user_id      INT NOT NULL,
    question_id  INT NOT NULL,
    answer       CHAR(1) NOT NULL,
    is_correct   TINYINT(1) NOT NULL,
    answered_at  DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
    PRIMARY KEY (user_id, question_id),
    FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE CASCADE,
    FOREIGN KEY (question_id) REFERENCES quiz_items(id) ON DELETE CASCADE
) ENGINE=InnoDB;

-- ---------------------------------------------------------------------
-- Streaks — one row per user.
-- ---------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS streaks (
    user_id          INT PRIMARY KEY,
    current_streak   INT NOT NULL DEFAULT 0,
    longest_streak   INT NOT NULL DEFAULT 0,
    last_active_date DATE NULL,
    FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE CASCADE
) ENGINE=InnoDB;

